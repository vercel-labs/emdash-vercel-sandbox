import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { installRuntime } from '../src/mac-install.mjs';
const hash = b => createHash('sha256').update(b).digest('hex');
test('atomic fresh install survives concurrent callers, ignores an interrupted staging copy, and refuses changed installed bytes',async t=>{
 const tmp=await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(),'emdash-installer-')));t.after(()=>fs.rm(tmp,{recursive:true,force:true}));
 const resources=path.join(tmp,'resources');await fs.mkdir(path.join(resources,'payload/app/bin'),{recursive:true});
 const files=[{path:'node',content:'fixture-node'},{path:'app/bin/emdash-sandbox.mjs',content:'fixture-entry'}];
 for(const f of files)await fs.writeFile(path.join(resources,'payload',f.path),f.content);
 await fs.writeFile(path.join(resources,'runtime-manifest.json'),JSON.stringify({schema:1,files:files.map(f=>({path:f.path,sha256:hash(f.content),executable:false}))}));
 const root=path.join(tmp,'runtime');await fs.mkdir(root,{mode:0o700});await fs.mkdir(path.join(root,'.interrupted-copy'));
 const installed=await Promise.all([installRuntime(resources,root),installRuntime(resources,root)]);assert.equal(installed[0],installed[1]);
 assert.equal(await fs.readFile(path.join(installed[0],'node'),'utf8'),'fixture-node');
 await fs.writeFile(path.join(installed[0],'extra.js'),'unexpected');
 await assert.rejects(installRuntime(resources,root),/unexpected files/);
 await fs.unlink(path.join(installed[0],'extra.js'));
 await fs.appendFile(path.join(installed[0],'node'),'bad');await assert.rejects(installRuntime(resources,root),/integrity/);
 await fs.rename(path.join(resources,'payload'),path.join(resources,'original-payload'));
 await fs.symlink(path.join(resources,'original-payload'),path.join(resources,'payload'));
 await assert.rejects(installRuntime(resources,path.join(tmp,'linked-payload-runtime')),/canonical directory/);
 await fs.unlink(path.join(resources,'payload'));
 await fs.rename(path.join(resources,'original-payload'),path.join(resources,'payload'));
 const raw=JSON.parse(await fs.readFile(path.join(resources,'runtime-manifest.json')));raw.files[0].path='../outside';await fs.writeFile(path.join(resources,'runtime-manifest.json'),JSON.stringify(raw));
 await assert.rejects(installRuntime(resources,path.join(tmp,'other-runtime')),/manifest/);
});
